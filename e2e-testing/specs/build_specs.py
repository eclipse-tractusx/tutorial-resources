"""Builds the spec pages from specs/<product>.yaml, so the two cannot drift.

    python specs/build_specs.py                  # write docs/specs/
    python specs/build_specs.py --check          # fail if docs/specs/ is out of date
    python specs/build_specs.py --refresh-steps  # rewrite known-steps.txt from `testlab docs --json`

Every spec is checked against spec.schema.json, its product must exist in
catalog/products.json, and every step it names must be a step TestLab knows
(specs/known-steps.txt). A spec that names an invented step does not build.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

import yaml
from jsonschema import Draft202012Validator

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = ROOT / "docs" / "specs"
PRODUCTS = ROOT / "catalog" / "products.json"
KNOWN_STEPS = HERE / "known-steps.txt"
REPO_BLOB = "https://github.com/eclipse-tractusx/tutorial-resources/blob/main/e2e-testing"

KIND_LABEL = {"journey": "Journey", "positive": "Positive", "negative": "Negative", "contract": "Contract"}
INFRA_LABEL = {"connector": "connector", "dtr": "Digital Twin Registry"}
VARIABLE_KIND = {
    "input": "`variable/type/string`, `source: input`",
    "asset": "`config/connector/asset`",
    "policy": "`config/connector/policy`",
}

NOTICE = """## NOTICE

This work is licensed under the [CC-BY-4.0](https://creativecommons.org/licenses/by/4.0/legalcode).

- SPDX-License-Identifier: CC-BY-4.0
- SPDX-FileCopyrightText: 2026 Contributors to the Eclipse Foundation
- Source URL: <https://github.com/eclipse-tractusx/tutorial-resources>
"""

GENERATED = "<!-- Generated by specs/build_specs.py from specs/{source}. Do not edit by hand. -->"


# --------------------------------------------------------------------------- checks


def known_steps() -> set[str]:
    lines = KNOWN_STEPS.read_text(encoding="utf-8").splitlines()
    return {line.strip() for line in lines if line.strip() and not line.startswith("#")}


def load_specs() -> list[tuple[Path, dict]]:
    schema = json.loads((HERE / "spec.schema.json").read_text(encoding="utf-8"))
    validator = Draft202012Validator(schema)
    products = {p["id"]: p for p in json.loads(PRODUCTS.read_text(encoding="utf-8"))["products"]}
    steps = known_steps()
    problems: list[str] = []
    specs: list[tuple[Path, dict]] = []
    for path in sorted(HERE.glob("*.yaml")):
        spec = yaml.safe_load(path.read_text(encoding="utf-8"))
        errors = sorted(validator.iter_errors(spec), key=lambda e: list(e.path))
        for error in errors:
            where = "/".join(str(part) for part in error.path) or "(root)"
            problems.append(f"{path.name}: {where}: {error.message}")
        if errors:
            continue
        problems += check_spec(path.name, spec, products, steps)
        specs.append((path, spec))
    if problems:
        print("\n".join(problems), file=sys.stderr)
        raise SystemExit(1)
    if not specs:
        print("no specs found", file=sys.stderr)
        raise SystemExit(1)
    return specs


def check_spec(name: str, spec: dict, products: dict, steps: set[str]) -> list[str]:
    problems = []
    if f"{spec['product']}.yaml" != name:
        problems.append(f"{name}: the file must be named after its product: {spec['product']}.yaml")
    if spec["product"] not in products:
        problems.append(f"{name}: product '{spec['product']}' is not in catalog/products.json")
    files = [test["file"] for test in spec["tests"]]
    ids = [test["id"] for test in spec["tests"]]
    for label, values in (("file", files), ("id", ids)):
        problems += [f"{name}: test {label} '{v}' is used twice" for v in sorted({v for v in values if values.count(v) > 1})]
    required = [test for test in spec["tests"] if not test.get("optional")]
    kinds = {kind for test in required for kind in test["kinds"]}
    if not kinds & {"journey", "positive"}:
        problems.append(f"{name}: the required tests need at least one positive or journey test")
    if "negative" not in kinds:
        problems.append(f"{name}: the required tests need at least one negative test")
    for test in spec["tests"]:
        for phase in ("setup", "execution", "teardown"):
            for step in test.get(phase, []):
                if step["step"] not in steps:
                    problems.append(
                        f"{name}: {test['file']} {phase}: '{step['step']}' is not a TestLab step (see known-steps.txt)"
                    )
    for entry in spec["breakItOnPurpose"]:
        if entry["test"] not in files:
            problems.append(f"{name}: breakItOnPurpose names the unknown test '{entry['test']}'")
    return problems


# --------------------------------------------------------------------------- pages


def code(text: str) -> str:
    return f"`{text}`"


def folder_tree(spec: dict) -> str:
    tck = spec["tck"]
    lines = [f"{tck['folder']}/", "├── index.yaml                # the manifest", "├── tests/"]
    tests = spec["tests"]
    for i, test in enumerate(tests):
        branch = "└──" if i == len(tests) - 1 else "├──"
        mark = "   (optional)" if test.get("optional") else ""
        lines.append(f"│   {branch} {test['file']}{mark}")
    extra = []
    if tck.get("schemas"):
        extra.append(("schemas/", [s["file"] for s in tck["schemas"]]))
    if tck.get("apis"):
        extra.append(("apis/", [f"{a['id']}.json" for a in tck["apis"]]))
    for j, (folder, entries) in enumerate(extra):
        last = j == len(extra) - 1
        lines.append(f"{'└──' if last else '├──'} {folder}")
        for k, entry in enumerate(entries):
            pad = "    " if last else "│   "
            lines.append(f"{pad}{'└──' if k == len(entries) - 1 else '├──'} {entry}")
    if not extra:
        lines[-1 - len(tests)] = lines[-1 - len(tests)].replace("├── tests/", "└── tests/")
        lines = [line.replace("│   ", "    ") if line.startswith("│") else line for line in lines]
    lines += ["", ".tractusx                     # e2eTest: tck/e2e", ".github/workflows/e2e-test.yml"]
    return "\n".join(lines)


def infra(sides: list[str]) -> str:
    return ", ".join(INFRA_LABEL[s] for s in sides) if sides else "nothing"


def step_table(steps: list[dict]) -> list[str]:
    lines = ["| # | What happens | Step | Must be true |", "| --- | --- | --- | --- |"]
    for i, step in enumerate(steps, 1):
        checks = "<br/>".join(f"☐ {c}" for c in step.get("check", [])) or "–"
        lines.append(f"| {i} | {step['do']} | {code(step['step'])} | {checks} |")
    return lines


def render_test(n: int, test: dict) -> list[str]:
    kinds = " · ".join(KIND_LABEL[k] for k in test["kinds"])
    title = f"### Test {n} · {test['name']}"
    if test.get("optional"):
        title += " (optional)"
    lines = [
        title,
        "",
        f"`tests/{test['file']}` · id `{test['id']}` · **{kinds}**",
        "",
        f"**Proves:** {test['proves']}",
        "",
    ]
    for phase in ("setup", "execution", "teardown"):
        if test.get(phase):
            lines += [f"**{phase}**", "", *step_table(test[phase]), ""]
    return lines


def render_prompt(spec: dict, name: str) -> str:
    tck = spec["tck"]
    required = [t for t in spec["tests"] if not t.get("optional")]
    files = ", ".join(t["file"] for t in required)
    return "\n".join(
        [
            f"Build the E2E test project for {name} in {tck['folder']}, exactly as the spec",
            f"{spec['product']}.yaml describes it. The manifest id is {tck['id']}; every test",
            "file repeats it as namespace. Write the required tests first: " + files + ".",
            "Use only the steps the spec names, and look each one up in the block catalog",
            "before you write its inputs. Every check in the spec becomes one validate entry.",
            "Addresses, BPNs and secrets are variables, never values in a test.",
            "Compile after each file and fix what the compiler reports.",
        ]
    )


def render_spec(path: Path, spec: dict, product: dict) -> str:
    tck = spec["tck"]
    status = "Proven" if spec["status"] == "proven" else "Draft"
    lines = [
        GENERATED.format(source=path.name),
        "",
        f"# {product['name']}: E2E test spec",
        "",
        f"> **{spec['inOneSentence'].strip()}**",
        "",
        f"Repository: [`{product['repository'].rsplit('/', 1)[-1]}`]({product['repository']}) · "
        f"Spec {spec['specVersion']} · **{status}** · "
        f"[Raw spec for your AI]({path.name}) · [All specs](index.md)",
        "",
    ]
    if spec.get("statusNote"):
        lines += ["> [!NOTE]", f"> {spec['statusNote'].strip()}", ""]
    lines += [
        "## 1 · The product in brief",
        "",
        spec["whatItDoes"].strip(),
        "",
        "## 2 · The journey the test tells",
        "",
        "| Side | Played by |",
        "| --- | --- |",
        f"| **Your side** ([SUT](../reference/glossary.md#sut)) | {spec['journey']['yourSide']} |",
        f"| **Partner side** ([engine](../reference/glossary.md#engine)) | {spec['journey']['partnerSide']} |",
        "",
        *[f"{i}. {move}" for i, move in enumerate(spec["journey"]["moves"], 1)],
        "",
        "## 3 · The TCK you deliver",
        "",
        "```text",
        folder_tree(spec),
        "```",
        "",
        "| Manifest field | Value |",
        "| --- | --- |",
        "| `kind` · `syntax` | `tck` · `v1-alpha` |",
        f"| `id` | `{tck['id']}` |",
        "| `metadata.license` | `Apache-2.0` |",
        "| `metadata.standards` | "
        + (", ".join(f"`{s['id']}` `{s['version']}`" for s in tck.get("standards", [])) or "`[]`")
        + " |",
        "| `dataspace` | `ecosystem: Catena-X`, `version: saturn` |",
        f"| `infrastructure.engine` | {infra(tck['infrastructure']['engine'])} |",
        f"| `infrastructure.sut` | {infra(tck['infrastructure']['sut'])} |",
        "",
    ]
    if tck["variables"]:
        lines += ["**Variables** (`env.variables`)", "", "| id | Kind | What it is | Example | In the workflow |", "| --- | --- | --- | --- | --- |"]
        for v in tck["variables"]:
            scope = f", `scope: {v['scope']}`" if v.get("scope") else ""
            lines.append(
                f"| `{v['id']}` | {VARIABLE_KIND[v['kind']]}{scope} | {' '.join(v['what'].split())} "
                f"| {code(v['example']) if v.get('example') else '–'} | {v.get('inWorkflow', 'Written in the manifest' if v['kind'] != 'input' else 'Supplied when the TCK runs')} |"
            )
        lines.append("")
    if tck.get("schemas"):
        lines += ["**Schemas** (`env.schemas`)", "", "| id | File | What it checks | Copy it from |", "| --- | --- | --- | --- |"]
        for s in tck["schemas"]:
            lines.append(f"| `{s['id']}` | `schemas/{s['file']}` | {s['what']} | {code(s['copyFrom']) if s.get('copyFrom') else '–'} |")
        lines.append("")
    if tck.get("apis"):
        lines += ["**API documents** (`env.apis`)", "", "| id | What it is | Source |", "| --- | --- | --- |"]
        for a in tck["apis"]:
            lines.append(f"| `{a['id']}` | {' '.join(a['what'].split())} | <{a['source']}> |")
        lines.append("")
    workflow = tck.get("workflow", {})
    run = "Yes" if tck.get("runsInWorkshop") else "No: build, validate and compile today; run where the product is deployed"
    lines += [
        f"**Runs in the workshop:** {run}. "
        f"**Workflow input `run-in-toolbox`:** `{str(workflow.get('runInToolbox', True)).lower()}`."
        + (f" {workflow['note']}" if workflow.get("note") else ""),
        "",
        "## 4 · The tests",
        "",
        "Every row is one step. Every ☐ is one `validate` entry. The step names are TestLab's own: "
        "look each one up in the IDE's block catalog for its inputs.",
        "",
    ]
    for n, test in enumerate(spec["tests"], 1):
        lines += render_test(n, test)
    lines += [
        "## 5 · Break it on purpose",
        "",
        "A check that cannot fail proves nothing. Make each change once, see the test go red for this reason, "
        "and change it back.",
        "",
        "| Test | Change | Expect |",
        "| --- | --- | --- |",
        *[f"| `{b['test']}` | {b['change']} | {b['expect']} |" for b in spec["breakItOnPurpose"]],
        "",
    ]
    if spec.get("pitfalls"):
        lines += ["## 6 · Watch out", "", *[f"- {p}" for p in spec["pitfalls"]], ""]
    if spec.get("notInScope"):
        lines += ["## 7 · Not in this spec", "", *[f"- {p}" for p in spec["notInScope"]], ""]
    lines += [
        "## 8 · Give it to your assistant",
        "",
        f"Attach or paste [the raw spec]({path.name}), then send:",
        "",
        "```text",
        render_prompt(spec, product["name"]),
        "```",
        "",
        "## Done when",
        "",
        "The [definition of done](index.md#done-when) for every product, and:",
        "",
        *[f"- [ ] `tests/{t['file']}` is green." for t in spec["tests"] if not t.get("optional")],
        "",
    ]
    if spec.get("sources"):
        lines += ["## Sources", "", *[f"- [{s['label']}]({s['url']})" for s in spec["sources"]], ""]
    lines += ["---", "", "[← All specs](index.md) · [Home](../index.md)", "", NOTICE]
    return "\n".join(lines)


def render_index(specs: list[tuple[Path, dict]], products: dict) -> str:
    rows = []
    for path, spec in specs:
        product = products[spec["product"]]
        required = [t for t in spec["tests"] if not t.get("optional")]
        optional = len(spec["tests"]) - len(required)
        tests = f"{len(required)}" + (f" + {optional} optional" if optional else "")
        run = "Yes" if spec["tck"].get("runsInWorkshop") else "Build and compile only"
        status = "Proven" if spec["status"] == "proven" else "Draft"
        rows.append(
            f"| [{product['name']}]({path.stem}.md) | {spec['inOneSentence'].strip()} | {tests} | {run} | {status} |"
        )
    return "\n".join(
        [
            GENERATED.format(source="*.yaml"),
            "",
            "# E2E test specs",
            "",
            "**You don't need to know your product.** Its spec says what the test must prove, which steps "
            "to use and what the finished TCK looks like. You and your assistant turn it into YAML, "
            "make it green and open the pull request.",
            "",
            "[Home](../index.md) · [Product catalog](../reference/catalog.md) · [Glossary](../reference/glossary.md)",
            "",
            "## Pick your product",
            "",
            "| Product | What the test proves | Tests | Runs in the workshop | Spec |",
            "| --- | --- | --- | --- | --- |",
            *rows,
            "",
            "**Proven:** a TCK built from the spec passed in GitHub Actions. **Draft:** not run end to end yet. "
            "If something in a draft does not hold, tell a facilitator: your finding fixes the spec.",
            "",
            "## Every spec has the same eight parts",
            "",
            "| Part | Tells you |",
            "| --- | --- |",
            "| 1 · The product | What it does, for someone who has never heard of it |",
            "| 2 · The journey | The story, move by move, between your side and the partner side |",
            "| 3 · The TCK you deliver | Folder, manifest fields, variables, schemas |",
            "| 4 · The tests | Each test, phase by phase: step, what happens, what must be true |",
            "| 5 · Break it on purpose | How to see each check fail for the right reason |",
            "| 6 · Watch out | What went wrong before |",
            "| 7 · Not in this spec | What you do not need to test today |",
            "| 8 · Give it to your assistant | The prompt, and the raw spec to attach |",
            "",
            "## The target TCK, for every product",
            "",
            "```text",
            "<product repository>/",
            "├── tck/e2e/",
            "│   ├── index.yaml        # the manifest: id <product>-e2e, kind tck, syntax v1-alpha",
            "│   ├── tests/            # one file per test, each with setup, execution, teardown",
            "│   └── schemas/          # only when a test checks an answer against a JSON schema",
            "├── .tractusx             # e2eTest: tck/e2e",
            "└── .github/workflows/e2e-test.yml",
            "```",
            "",
            "| Rule | Why |",
            "| --- | --- |",
            "| At least one **positive** test and one **negative** test | A test that only ever says yes proves nothing |",
            "| Each test **file** is listed under `tests:` in the manifest, and repeats its `id` as `namespace` | Otherwise it is not part of the project |",
            "| Only **steps the spec names** | They are TestLab's ready-made steps. An invented step does not compile |",
            "| Every **check** in the spec is a `validate` entry | The checks are what the test proves |",
            "| **Addresses, BPNs and secrets** are variables or `infrastructure.*` references | The same test runs in the workshop, in CI and at a partner |",
            "| What `setup` **creates**, `teardown` **removes** | The test must pass twice in a row |",
            "| `metadata.license: Apache-2.0`, with the Eclipse Tractus-X header in every file | It is contributed to an Eclipse project |",
            "",
            "## Done when",
            "",
            "- [ ] **Compile** in the IDE is green (or `testlab validate tck/e2e/index.yaml` reports no issues).",
            "- [ ] The required tests of your spec pass against your connectors, or, for a product that does "
            "not run in the workshop, compile.",
            "- [ ] You broke each check once on purpose and saw it fail.",
            "- [ ] The pull request to the product's repository is open, with `tck/e2e/`, the `.tractusx` "
            "link and the workflow, and its check is green.",
            "",
            "## Write a spec for another product",
            "",
            "Copy a spec in `specs/`, keep the eight parts, and run `python specs/build_specs.py`. "
            "The script checks the spec against `specs/spec.schema.json` and refuses any step "
            "that TestLab does not have.",
            "",
            NOTICE,
        ]
    )


# --------------------------------------------------------------------------- main


def build() -> dict[Path, str]:
    specs = load_specs()
    products = {p["id"]: p for p in json.loads(PRODUCTS.read_text(encoding="utf-8"))["products"]}
    files = {OUT / "index.md": render_index(specs, products)}
    for path, spec in specs:
        files[OUT / f"{path.stem}.md"] = render_spec(path, spec, products[spec["product"]])
        files[OUT / path.name] = path.read_text(encoding="utf-8")
    return files


def refresh_steps() -> None:
    testlab = shutil.which("testlab")
    if not testlab:
        print("testlab is not installed: pip install tractusx-testlab --pre", file=sys.stderr)
        raise SystemExit(1)
    version = subprocess.run(
        [sys.executable, "-m", "pip", "show", "tractusx-testlab"], capture_output=True, text=True, check=False
    ).stdout
    version = next((line.split(":", 1)[1].strip() for line in version.splitlines() if line.startswith("Version:")), "?")
    steps = json.loads(subprocess.run([testlab, "docs", "--json"], capture_output=True, text=True, check=True).stdout)
    names = sorted(step["step_type"] for step in steps)
    header = [
        f"# Steps of tractusx-testlab {version}, from `testlab docs --json`.",
        "# Rewrite with: python specs/build_specs.py --refresh-steps",
    ]
    KNOWN_STEPS.write_text("\n".join(header + names) + "\n", encoding="utf-8")
    print(f"wrote {KNOWN_STEPS.relative_to(ROOT)} ({len(names)} steps)")


def main() -> None:
    if "--refresh-steps" in sys.argv:
        refresh_steps()
        return
    files = build()
    if "--check" in sys.argv:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        stale += [p for p in OUT.glob("*") if p not in files]
        if stale:
            for p in stale:
                print(f"{p.relative_to(ROOT)} is out of date: run python specs/build_specs.py", file=sys.stderr)
            raise SystemExit(1)
        print(f"spec pages are up to date ({len(files) - 1} files)")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for p in OUT.glob("*"):
        if p not in files:
            p.unlink()
    for p, text in files.items():
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
