"""Builds the catalog page from products.json, so the two cannot drift.

    python catalog/build_catalog.py            # write docs/reference/catalog.md
    python catalog/build_catalog.py --check    # fail if the page is out of date

Also checks products.json and assignments.json against their schemas, and
that every assignment names a product that exists.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from jsonschema import Draft202012Validator

HERE = Path(__file__).resolve().parent
PAGE = HERE.parent / "docs" / "reference" / "catalog.md"

DIFFICULTY = {"starter": "Starter", "intermediate": "Intermediate", "advanced": "Advanced"}
NEEDS = {
    "connector": "connector",
    "dtr": "Digital Twin Registry",
    "wallet": "wallet",
    "bdrs": "BDRS",
    "iam": "identity provider",
    "portal": "Portal",
    "bpdm": "BPDM",
    "discovery-finder": "Discovery Finder",
    "bpn-discovery": "BPN Discovery",
    "semantic-hub": "Semantic Hub",
    "submodel-server": "submodel server",
    "irs": "IRS",
    "kafka": "Kafka",
    "database": "database",
    "kubernetes": "Kubernetes cluster",
    "browser": "browser",
}

NOTICE = """## NOTICE

This work is licensed under the [CC-BY-4.0](https://creativecommons.org/licenses/by/4.0/legalcode).

- SPDX-License-Identifier: CC-BY-4.0
- SPDX-FileCopyrightText: 2026 Contributors to the Eclipse Foundation
- Source URL: <https://github.com/eclipse-tractusx/tutorial-resources>
"""


def load(name: str) -> dict:
    data = json.loads((HERE / name).read_text(encoding="utf-8"))
    schema = json.loads((HERE / name.replace(".json", ".schema.json")).read_text(encoding="utf-8"))
    errors = sorted(Draft202012Validator(schema).iter_errors(data), key=lambda e: list(e.path))
    if errors:
        for error in errors:
            where = "/".join(str(part) for part in error.path) or "(root)"
            print(f"{name}: {where}: {error.message}", file=sys.stderr)
        raise SystemExit(1)
    return data


def check_references(products: dict, assignments: dict) -> None:
    ids = [product["id"] for product in products["products"]]
    problems = [f"products.json: id '{i}' is used twice" for i in sorted({i for i in ids if ids.count(i) > 1})]
    teams = [entry["team"] for entry in assignments["assignments"]]
    problems += [f"assignments.json: team '{t}' is listed twice" for t in sorted({t for t in teams if teams.count(t) > 1})]
    problems += [
        f"assignments.json: team '{entry['team']}' names the unknown product '{entry['productId']}'"
        for entry in assignments["assignments"]
        if entry["productId"] not in ids
    ]
    if problems:
        print("\n".join(problems), file=sys.stderr)
        raise SystemExit(1)


def repo_link(url: str) -> str:
    return f"[`{url.rsplit('/', 1)[-1]}`]({url})"


def row(product: dict) -> str:
    needs = ", ".join(NEEDS[need] for need in product["needs"])
    umbrella = "Yes" if product["runsInUmbrella"] else "No"
    return (
        f"| **{product['name']}**<br/>{repo_link(product['repository'])} "
        f"| {product['scenario']} | {needs} | {umbrella} | {DIFFICULTY[product['difficulty']]} |"
    )


def table(products: list[dict]) -> list[str]:
    return [
        "| Product | Suggested E2E scenario | Needs | In the developer toolbox | Difficulty |",
        "| --- | --- | --- | --- | --- |",
        *[row(product) for product in products],
    ]


def render(data: dict) -> str:
    products = data["products"]
    fit = [product for product in products if product["fitsWorkshop"]]
    later = [product for product in products if not product["fitsWorkshop"]]
    source = data["generatedFrom"]
    environment = ", ".join(NEEDS[need] for need in data["workshopEnvironment"])
    lines = [
        "<!-- Generated by catalog/build_catalog.py from catalog/products.json. Do not edit by hand. -->",
        "",
        "# Product catalog",
        "",
        f"{len(products)} Eclipse Tractus-X products that should get an E2E test. "
        f"{len(fit)} of them can be built **and run** in the workshop.",
        "",
        f"Collected on {source['collectedOn']} from the `{source['organization']}` organization: "
        "the repository list, each repository's `.tractusx` metafile and the Umbrella chart.",
        "",
        "[Home](../index.md) · [Glossary](glossary.md)",
        "",
        "## Fits the workshop",
        "",
        f"These need only what every team gets: {environment}.",
        "",
        *table(fit),
        "",
        "## Needs more than the workshop environment",
        "",
        "Build, validate and compile the test in the workshop. Run it where the product is deployed, "
        "or in CI once the workflow can bring the product up.",
        "",
        *table(later),
        "",
        "## What is missing for each of them",
        "",
        "| Product | To run its test you also need |",
        "| --- | --- |",
        *[f"| {product['name']} | {product['workshopNote']} |" for product in later],
        "",
        "## More scenarios",
        "",
        "For a second team on the same product, or for your next pull request.",
        "",
    ]
    for product in products:
        if product.get("moreScenarios"):
            lines += [f"**{product['name']}**", ""]
            lines += [f"- {scenario}" for scenario in product["moreScenarios"]]
            lines.append("")
    lines += [
        "## Tests the repositories already have",
        "",
        "Read them before you write a scenario: they show what the maintainers consider important.",
        "",
        "| Product | Existing tests |",
        "| --- | --- |",
        *[
            f"| {product['name']} | {', '.join(f'`{item}`' for item in product['existingTests'])} |"
            for product in products
            if product.get("existingTests")
        ],
        "",
        "## Not in the list",
        "",
        "| Repository | Why |",
        "| --- | --- |",
        *[f"| {repo_link(entry['repository'])} | {entry['reason']} |" for entry in data.get("excluded", [])],
        "",
        "## Change the catalog",
        "",
        "Edit `catalog/products.json`, then run `python catalog/build_catalog.py`. "
        "The file is checked against `catalog/products.schema.json`. "
        "Team assignments live in `catalog/assignments.json`, so this list stays stable.",
        "",
        NOTICE,
    ]
    return "\n".join(lines)


def main() -> None:
    products = load("products.json")
    assignments = load("assignments.json")
    check_references(products, assignments)
    page = render(products)
    if "--check" in sys.argv:
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page:
            print(f"{PAGE.relative_to(HERE.parent)} is out of date: run python catalog/build_catalog.py", file=sys.stderr)
            raise SystemExit(1)
        print("catalog page is up to date")
        return
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(page, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
